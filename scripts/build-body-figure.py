#!/usr/bin/env python3
"""
Builds src/components/body/figure-art.ts from the hand-drawn body figure
(src/components/body/art/figure.svg + anchors.json).

The figure is original artwork drawn for Demify from anatomical proportions
(style inspired by classic educational skeleton illustrations; nothing
traced or embedded). Re-run after editing the SVG:

    python3 scripts/build-body-figure.py
"""
import json
import re
from pathlib import Path
from xml.dom import minidom

ROOT = Path(__file__).resolve().parent.parent
ART = ROOT / "src/components/body/art"
OUT = ROOT / "src/components/body/figure-art.ts"

# Bottom -> top stacking for the invisible click layer: organs must win over
# the ribs drawn in front of them, bones over the body surface.
HIT_ORDER = ["skin", "muscles", "skeleton", "blood", "gut", "lungs", "heart", "brain", "eyes"]


def rename(markup: str) -> str:
    # Keep the figure's ids/classes from clashing with the monitor's "dm-" CSS.
    return re.sub(r'(?<=[\s"\'#(.])dm(?=[A-Za-z0-9_-])', "bf", markup)


def strip_ids(markup: str) -> str:
    return re.sub(r'\sid="[^"]*"', "", markup)


svg = rename((ART / "figure.svg").read_text())
doc = minidom.parseString(svg)
root = doc.documentElement
viewbox = root.getAttribute("viewBox")

inner = "".join(node.toxml() for node in root.childNodes if node.nodeType == node.ELEMENT_NODE)

hit: dict[str, list[str]] = {r: [] for r in HIT_ORDER}
for g in doc.getElementsByTagName("g"):
    region = g.getAttribute("data-region")
    if region:
        hit[region].append(strip_ids(g.toxml()))
    elif g.getAttribute("id") == "body-core":
        # The whole body surface counts as skin where nothing else is hit.
        hit["skin"].insert(0, strip_ids(g.toxml()))

anchors = json.loads((ART / "anchors.json").read_text())

ts = [
    "// GENERATED by scripts/build-body-figure.py from src/components/body/art/figure.svg. Do not edit by hand.",
    'import type { BodyRegionId } from "@/lib/types";',
    "",
    f"export const FIGURE_VIEWBOX = {json.dumps(viewbox)};",
    "",
    "/** Complete artwork (styles, defs, silhouette, organs, skeleton). Static, trusted markup. */",
    f"export const FIGURE_ART = {json.dumps(inner)};",
    "",
    "/** Per-region markup for the invisible click layer, in stacking order (bottom -> top). */",
    "export const FIGURE_HIT: Array<[BodyRegionId, string]> = [",
]
for r in HIT_ORDER:
    ts.append(f"  [{json.dumps(r)}, {json.dumps(''.join(hit[r]))}],")
ts += [
    "];",
    "",
    "/** Centre + radius of the pulsing status rings, in viewBox units. */",
    f"export const FIGURE_ANCHORS: Record<BodyRegionId, Array<[number, number, number]>> = {json.dumps(anchors)};",
    "",
]
OUT.write_text("\n".join(ts))
print(f"wrote {OUT.relative_to(ROOT)} ({OUT.stat().st_size // 1024} KB)")
