import { CircleCheck, CircleDashed, OctagonExclamationPoint, TriangleExclamationPoint } from "lucide-react";
import type { Status } from "@/lib/types";
import { STATUS_LABEL, STATUS_TEXT } from "@/components/ui";

/**
 * Status glyph with a distinct shape per level (check / triangle / octagon /
 * dashed circle), so status is never conveyed by colour alone.
 */
export function StatusIcon({ status, size = 14, className = "" }: { status: Status; size?: number; className?: string }) {
  const Icon =
    status === "critical"
      ? OctagonExclamationPoint
      : status === "caution"
        ? TriangleExclamationPoint
        : status === "nominal"
          ? CircleCheck
          : CircleDashed;
  return (
    <Icon
      size={size}
      className={`shrink-0 ${STATUS_TEXT[status]} ${className}`}
      aria-label={STATUS_LABEL[status]}
      role="img"
    />
  );
}

/** Small tag that marks demo/simulated values honestly. */
export function SimulatedTag({ label = "simulated telemetry" }: { label?: string }) {
  return (
    <span
      className="inline-flex items-center rounded border border-dashed border-muted/50 px-1.5 py-px text-[10px] uppercase tracking-wider text-muted"
      title="Generated by the demo telemetry simulator, not measured. Real device or crew entries replace it."
    >
      {label}
    </span>
  );
}

/** Tag for crew-entered / device values. */
export function SourceTag({ source }: { source: "manual" | "sensor" | string }) {
  return (
    <span className="inline-flex items-center rounded border border-accent/40 px-1.5 py-px text-[10px] uppercase tracking-wider text-accent">
      {source === "manual" ? "crew entry" : source}
    </span>
  );
}
