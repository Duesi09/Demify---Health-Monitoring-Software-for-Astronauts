import { OctagonAlert, SquareCheck, SquareDashed, TriangleAlert } from "lucide-react";
import type { Status } from "@/lib/types";
import { STATUS_LABEL, STATUS_TEXT } from "@/components/ui";
import { SOURCE_LABEL } from "./format";

/**
 * Status glyph with a distinct shape per level, matching StatusBadge and the
 * patient monitor: squared check (nominal), triangle (caution), octagon
 * (critical), dashed square (no data). Status is never conveyed by colour
 * alone.
 */
export function StatusIcon({ status, size = 14, className = "" }: { status: Status; size?: number; className?: string }) {
  const Icon =
    status === "critical"
      ? OctagonAlert
      : status === "caution"
        ? TriangleAlert
        : status === "nominal"
          ? SquareCheck
          : SquareDashed;
  return (
    <Icon
      size={size}
      strokeWidth={2.25}
      className={`shrink-0 ${STATUS_TEXT[status]} ${className}`}
 aria-label={STATUS_LABEL[status]}
 role="img"
 />
 );
}

/** Squared, tag (monitor style, never a rounded pill). */
const TAG =
"inline-flex h-[18px] shrink-0 items-center rounded-[4px] px-1.5 text-[9.5px] font-semibold leading-none";

/**
 * SIMULATED data label (dashed = synthetic): values from the demo telemetry
 * generator. `prefix` names the value when one tile mixes sources ("systolic").
 */
export function SimulatedTag({ prefix, label = "SIMULATED" }: { prefix?: string; label?: string }) {
 return (
 <span
 className={`${TAG} border border-dashed border-muted/60 text-muted`}
      title="SIMULATED: generated by the demo telemetry simulator, not measured. A DEVICE reading or a crew entry replaces it."
    >
      {prefix ? `${prefix} ${label}` : label}
    </span>
  );
}

/** Data label for real readings: DEVICE (posted by a sensor or gateway) or a crew entry. */
export function SourceTag({ source, prefix }: { source: "manual" | "sensor" | string; prefix?: string }) {
  const label = source === "manual" ? SOURCE_LABEL.manual : source === "sensor" ? SOURCE_LABEL.sensor : source;
  const title =
    source === "manual"
      ? "Entered by the crew in the daily check-in"
      : source === "sensor"
        ? "DEVICE: posted by a sensor or gateway to /api/readings"
        : undefined;
  return (
    <span className={`${TAG} text-accent ring-1 ring-inset ring-accent/45`} title={title}>
      {prefix ? `${prefix} ${label}` : label}
    </span>
  );
}

/** Amber tag for training scenarios, so a drill is never mistaken for a real emergency. */
export function DrillTag({ label = "Training scenario", className = "" }: { label?: string; className?: string }) {
  return (
    <span
      className={`${TAG} bg-[#ffcc00] text-[#1c1400] ${className}`}
      title="Training scenario: simulated drill, not a real emergency"
    >
      {label}
    </span>
  );
}
